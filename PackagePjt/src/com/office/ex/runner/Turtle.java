package com.office.ex.runner;

/**
 * 거북이 러너. 달리기와 멈추기 동작을 콘솔 출력으로 보여 준다.
 */
public class Turtle {
	
	/** 거북이가 달리는 동작을 출력한다. */
	public void run() {
		System.out.println("[Turtle] run()");
		
		System.out.println("거북이는 엉금 엉금~");
		
	}

	/** 거북이가 멈추는 동작을 출력한다. */
	public void stop() {
		System.out.println("[Turtle] stop()");
		
		System.out.println("거북이 천천히 정지");
		
	}
	
	
}
